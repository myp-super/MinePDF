const DICTS: Record<Lang, Dict> = { 'zh-CN': zh, 'en-US': en };

/** Translation hook: re-renders when the language setting changes. */
export function useT(): (key: string, vars?: Record<string, string | number>) => string {
  const lang = useApp((s) => s.settings.language);
  const dict = DICTS[lang] ?? zh;
  return (key: string, vars?: Record<string, string | number>) => {
    let s = dict[key] ?? zh[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.split(`{${k}}`).join(String(v));
      }
    }
    return s;
  };
}

/** Map common main-process (Chinese) errors to the selected language. */
export function translateError(lang: Lang, msg: string): string {
  if (lang === 'zh-CN') return msg;
  const map: Array<[string, string]> = [
    ['文件夹名称不能为空', 'Folder name cannot be empty'],
    ['文件夹名称包含非法字符', 'Folder name contains invalid characters'],
    ['同级已存在同名文件夹', 'A folder with the same name already exists'],
    ['目标文件夹不存在', 'Target folder does not exist'],
    ['父文件夹不存在', 'Parent folder does not exist'],
    ['文件夹不存在', 'Folder does not exist'],
    ['PDF 记录不存在', 'PDF record does not exist'],
    ['标注不存在', 'Annotation does not exist'],
    ['该文件已存在于知识库中', 'This file is already in the library'],
    ['源文件不存在或已被移动', 'Source file is missing or was moved'],
    ['不能移动到自身', 'Cannot move into itself'],
    ['不能移动到自身的子文件夹', 'Cannot move into its own subfolder'],
    ['目标位置已存在同名文件夹', 'A folder with the same name exists at the target'],
  ];
  for (const [c, e] of map) {
    if (msg.includes(c)) return msg.replace(c, e);
  }
  return msg;
}

export function useTError(): (msg: string) => string {
  const lang = useApp((s) => s.settings.language);
  return (msg: string) => translateError(lang, msg);
}
